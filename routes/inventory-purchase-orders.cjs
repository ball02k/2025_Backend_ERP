// routes/inventory-purchase-orders.cjs
const express = require('express');
const { requirePerm } = require('../middleware/checkPermission.cjs');

module.exports = (prisma) => {
  const router = express.Router();

  // ============================================================================
  // PURCHASE ORDERS CRUD
  // ============================================================================

  // GET /api/purchase-orders - List purchase orders
  router.get('/', requirePerm('purchase_orders:view'), async (req, res, next) => {
    try {
      const { tenantId } = req.user;
      const {
        page = 1,
        limit = 50,
        status,
        supplierId,
        jobId,
        autoGenerated,
      } = req.query;

      const where = {
        tenantId,
        isDeleted: false,
      };

      if (status) where.status = status;
      if (supplierId) where.supplierId = supplierId;
      if (jobId) where.jobId = jobId;
      if (autoGenerated === 'true') where.autoGenerated = true;

      const skip = (parseInt(page) - 1) * parseInt(limit);
      const take = parseInt(limit);

      const [pos, total] = await Promise.all([
        prisma.inventoryPurchaseOrder.findMany({
          where,
          skip,
          take,
          include: {
            items: {
              include: {
                inventoryItem: {
                  select: { id: true, itemNumber: true, itemName: true },
                },
              },
            },
            job: {
              select: { id: true, jobNumber: true, title: true },
            },
          },
          orderBy: { createdAt: 'desc' },
        }),
        prisma.inventoryPurchaseOrder.count({ where }),
      ]);

      res.json({
        success: true,
        data: pos,
        meta: {
          total,
          page: parseInt(page),
          limit: parseInt(limit),
          totalPages: Math.ceil(total / parseInt(limit)),
        },
      });
    } catch (error) {
      next(error);
    }
  });

  // GET /api/purchase-orders/:id - Get single PO
  router.get('/:id', requirePerm('purchase_orders:view'), async (req, res, next) => {
    try {
      const { tenantId } = req.user;
      const { id } = req.params;

      const po = await prisma.inventoryPurchaseOrder.findFirst({
        where: { id, tenantId, isDeleted: false },
        include: {
          items: {
            include: {
              inventoryItem: true,
            },
          },
          job: {
            select: { id: true, jobNumber: true, title: true },
          },
        },
      });

      if (!po) {
        return res.status(404).json({
          success: false,
          error: { message: 'Purchase order not found' },
        });
      }

      res.json({ success: true, data: po });
    } catch (error) {
      next(error);
    }
  });

  // POST /api/purchase-orders - Create purchase order
  router.post('/', requirePerm('purchase_orders:create'), async (req, res, next) => {
    try {
      const { tenantId, userId } = req.user;
      const { items, ...poData } = req.body;

      // Generate PO number
      const count = await prisma.inventoryPurchaseOrder.count({ where: { tenantId } });
      const poNumber = `PO-INV-${new Date().getFullYear()}-${String(count + 1).padStart(5, '0')}`;

      // Calculate totals
      let subtotal = 0;
      const poItems = (items || []).map((item) => {
        const lineTotal = parseFloat(item.quantityOrdered) * parseFloat(item.unitPrice);
        subtotal += lineTotal;
        return {
          ...item,
          tenantId,
          lineTotal,
        };
      });

      const taxAmount = parseFloat(poData.taxAmount || 0);
      const shippingCost = parseFloat(poData.shippingCost || 0);
      const totalAmount = subtotal + taxAmount + shippingCost;

      const po = await prisma.inventoryPurchaseOrder.create({
        data: {
          ...poData,
          tenantId,
          poNumber,
          createdBy: userId,
          subtotal,
          taxAmount,
          shippingCost,
          totalAmount,
          items: {
            create: poItems,
          },
        },
        include: {
          items: {
            include: {
              inventoryItem: true,
            },
          },
        },
      });

      res.status(201).json({
        success: true,
        data: po,
        message: 'Purchase order created successfully',
      });
    } catch (error) {
      next(error);
    }
  });

  // POST /api/purchase-orders/auto-generate - Auto-generate PO for low stock
  router.post('/auto-generate', requirePerm('purchase_orders:create'), async (req, res, next) => {
    try {
      const { tenantId, userId } = req.user;

      // Find items below reorder level with auto-PO enabled
      const lowStockItems = await prisma.inventoryItem.findMany({
        where: {
          tenantId,
          isDeleted: false,
          autoGeneratePO: true,
          status: 'ACTIVE',
          quantityAvailable: {
            lte: prisma.inventoryItem.fields.reorderLevel,
          },
        },
      });

      if (lowStockItems.length === 0) {
        return res.json({
          success: true,
          data: [],
          message: 'No items below reorder level requiring purchase orders',
        });
      }

      // Group items by supplier
      const itemsBySupplier = lowStockItems.reduce((acc, item) => {
        const supplierId = item.primarySupplierId || 'unknown';
        if (!acc[supplierId]) acc[supplierId] = [];
        acc[supplierId].push(item);
        return acc;
      }, {});

      const createdPOs = [];

      // Create a PO for each supplier
      for (const [supplierId, items] of Object.entries(itemsBySupplier)) {
        const count = await prisma.inventoryPurchaseOrder.count({ where: { tenantId } });
        const poNumber = `PO-INV-${new Date().getFullYear()}-${String(count + 1 + createdPOs.length).padStart(5, '0')}`;

        const poItems = items.map((item) => {
          const qtyToOrder = parseFloat(item.reorderQuantity) || parseFloat(item.reorderLevel);
          const unitPrice = parseFloat(item.lastPurchasePrice) || parseFloat(item.unitCost) || 0;
          return {
            tenantId,
            inventoryItemId: item.id,
            itemName: item.itemName,
            itemSKU: item.sku,
            description: item.description,
            partNumber: item.partNumber,
            unitOfMeasure: item.unitOfMeasure,
            quantityOrdered: qtyToOrder,
            unitPrice,
            lineTotal: qtyToOrder * unitPrice,
            expectedDate: item.leadTimeDays
              ? new Date(Date.now() + item.leadTimeDays * 24 * 60 * 60 * 1000)
              : null,
          };
        });

        const subtotal = poItems.reduce((sum, item) => sum + parseFloat(item.lineTotal), 0);

        const po = await prisma.inventoryPurchaseOrder.create({
          data: {
            tenantId,
            poNumber,
            title: 'Auto-Generated Restock Order',
            description: `Automatic purchase order for ${items.length} low-stock items`,
            supplierId: supplierId !== 'unknown' ? supplierId : null,
            supplierName: supplierId !== 'unknown' ? `Supplier ${supplierId}` : 'Multiple Suppliers',
            status: 'DRAFT',
            priority: 'NORMAL',
            autoGenerated: true,
            generatedReason: `Stock below reorder level for ${items.length} items: ${items.map((i) => i.itemName).join(', ')}`,
            createdBy: userId,
            subtotal,
            totalAmount: subtotal,
            items: {
              create: poItems,
            },
          },
          include: {
            items: {
              include: {
                inventoryItem: true,
              },
            },
          },
        });

        createdPOs.push(po);
      }

      res.status(201).json({
        success: true,
        data: createdPOs,
        message: `${createdPOs.length} purchase order(s) generated automatically`,
      });
    } catch (error) {
      next(error);
    }
  });

  // PATCH /api/purchase-orders/:id - Update PO
  router.patch('/:id', requirePerm('purchase_orders:update'), async (req, res, next) => {
    try {
      const { tenantId } = req.user;
      const { id } = req.params;

      const existingPO = await prisma.inventoryPurchaseOrder.findFirst({
        where: { id, tenantId, isDeleted: false },
      });

      if (!existingPO) {
        return res.status(404).json({
          success: false,
          error: { message: 'Purchase order not found' },
        });
      }

      const po = await prisma.inventoryPurchaseOrder.update({
        where: { id },
        data: req.body,
        include: {
          items: {
            include: {
              inventoryItem: true,
            },
          },
        },
      });

      res.json({
        success: true,
        data: po,
        message: 'Purchase order updated successfully',
      });
    } catch (error) {
      next(error);
    }
  });

  // POST /api/purchase-orders/:id/approve - Approve PO
  router.post('/:id/approve', requirePerm('purchase_orders:approve'), async (req, res, next) => {
    try {
      const { tenantId, userId } = req.user;
      const { id } = req.params;

      const po = await prisma.inventoryPurchaseOrder.findFirst({
        where: { id, tenantId, isDeleted: false },
      });

      if (!po) {
        return res.status(404).json({
          success: false,
          error: { message: 'Purchase order not found' },
        });
      }

      if (po.status !== 'DRAFT' && po.status !== 'PENDING_APPROVAL') {
        return res.status(400).json({
          success: false,
          error: { message: 'Purchase order cannot be approved in its current status' },
        });
      }

      const updatedPO = await prisma.inventoryPurchaseOrder.update({
        where: { id },
        data: {
          status: 'APPROVED',
          approvedBy: userId,
          approvedAt: new Date(),
        },
        include: {
          items: {
            include: {
              inventoryItem: true,
            },
          },
        },
      });

      res.json({
        success: true,
        data: updatedPO,
        message: 'Purchase order approved successfully',
      });
    } catch (error) {
      next(error);
    }
  });

  // POST /api/purchase-orders/:id/receive - Receive items from PO
  router.post('/:id/receive', requirePerm('purchase_orders:receive'), async (req, res, next) => {
    try {
      const { tenantId, userId } = req.user;
      const { id } = req.params;
      const { items } = req.body; // Array of { itemId, quantityReceived }

      const po = await prisma.inventoryPurchaseOrder.findFirst({
        where: { id, tenantId, isDeleted: false },
        include: { items: { include: { inventoryItem: true } } },
      });

      if (!po) {
        return res.status(404).json({
          success: false,
          error: { message: 'Purchase order not found' },
        });
      }

      // Process each received item
      const updates = await prisma.$transaction(async (tx) => {
        const updatedItems = [];

        for (const receivedItem of items || []) {
          const poItem = po.items.find((i) => i.id === receivedItem.itemId);
          if (!poItem) continue;

          const qtyReceived = parseFloat(receivedItem.quantityReceived || 0);
          if (qtyReceived <= 0) continue;

          // Update PO item
          const updatedPOItem = await tx.inventoryPurchaseOrderItem.update({
            where: { id: poItem.id },
            data: {
              quantityReceived: { increment: qtyReceived },
              status:
                parseFloat(poItem.quantityReceived) + qtyReceived >= parseFloat(poItem.quantityOrdered)
                  ? 'RECEIVED'
                  : 'PARTIALLY_RECEIVED',
              receivedDate: new Date(),
            },
          });

          // Update inventory if item is linked
          if (poItem.inventoryItemId && poItem.inventoryItem) {
            const updatedInventory = await tx.inventoryItem.update({
              where: { id: poItem.inventoryItemId },
              data: {
                quantityInStock: { increment: qtyReceived },
                quantityAvailable: { increment: qtyReceived },
                lastRestockedAt: new Date(),
                lastPurchasePrice: parseFloat(poItem.unitPrice),
              },
            });

            // Create stock movement
            await tx.stockMovement.create({
              data: {
                tenantId,
                inventoryItemId: poItem.inventoryItemId,
                movementType: 'PURCHASE',
                quantityChange: qtyReceived,
                quantityBefore: parseFloat(poItem.inventoryItem.quantityInStock),
                quantityAfter: parseFloat(updatedInventory.quantityInStock),
                referenceType: 'PURCHASE_ORDER',
                referenceId: po.id,
                purchaseOrderId: po.id,
                reason: `Received from PO ${po.poNumber}`,
                performedBy: userId,
              },
            });
          }

          updatedItems.push(updatedPOItem);
        }

        // Check if all items are received
        const allItems = await tx.inventoryPurchaseOrderItem.findMany({
          where: { purchaseOrderId: id },
        });

        const allReceived = allItems.every(
          (item) => parseFloat(item.quantityReceived) >= parseFloat(item.quantityOrdered)
        );

        const partiallyReceived = allItems.some(
          (item) => parseFloat(item.quantityReceived) > 0
        );

        // Update PO status
        const updatedPO = await tx.inventoryPurchaseOrder.update({
          where: { id },
          data: {
            status: allReceived ? 'RECEIVED' : partiallyReceived ? 'PARTIALLY_RECEIVED' : po.status,
            receivedDate: allReceived ? new Date() : null,
          },
          include: {
            items: {
              include: {
                inventoryItem: true,
              },
            },
          },
        });

        return updatedPO;
      });

      res.json({
        success: true,
        data: updates,
        message: 'Items received successfully',
      });
    } catch (error) {
      next(error);
    }
  });

  // POST /api/purchase-orders/:id/cancel - Cancel PO
  router.post('/:id/cancel', requirePerm('purchase_orders:cancel'), async (req, res, next) => {
    try {
      const { tenantId, userId } = req.user;
      const { id } = req.params;
      const { reason } = req.body;

      const po = await prisma.inventoryPurchaseOrder.findFirst({
        where: { id, tenantId, isDeleted: false },
      });

      if (!po) {
        return res.status(404).json({
          success: false,
          error: { message: 'Purchase order not found' },
        });
      }

      if (po.status === 'RECEIVED' || po.status === 'CANCELLED') {
        return res.status(400).json({
          success: false,
          error: { message: 'Cannot cancel a received or already cancelled purchase order' },
        });
      }

      const updatedPO = await prisma.inventoryPurchaseOrder.update({
        where: { id },
        data: {
          status: 'CANCELLED',
          cancelledBy: userId,
          cancelledAt: new Date(),
          cancellationReason: reason,
        },
        include: {
          items: true,
        },
      });

      res.json({
        success: true,
        data: updatedPO,
        message: 'Purchase order cancelled successfully',
      });
    } catch (error) {
      next(error);
    }
  });

  // DELETE /api/purchase-orders/:id - Soft delete PO
  router.delete('/:id', requirePerm('purchase_orders:delete'), async (req, res, next) => {
    try {
      const { tenantId } = req.user;
      const { id } = req.params;

      const po = await prisma.inventoryPurchaseOrder.findFirst({
        where: { id, tenantId, isDeleted: false },
      });

      if (!po) {
        return res.status(404).json({
          success: false,
          error: { message: 'Purchase order not found' },
        });
      }

      await prisma.inventoryPurchaseOrder.update({
        where: { id },
        data: { isDeleted: true },
      });

      res.json({
        success: true,
        message: 'Purchase order deleted successfully',
      });
    } catch (error) {
      next(error);
    }
  });

  return router;
};
